from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


class ExplainFieldRequest(BaseModel):
    match_id: str = Field(..., description="Unique match identifier")
    delivery_id: str = Field(..., description="Delivery identifier to explain")
    fielder_id: Optional[str] = Field(None, description="Optional focus fielder identifier")


class ExplainChangeRequest(BaseModel):
    match_id: str = Field(..., description="Unique match identifier")
    delivery_id: str = Field(..., description="Target delivery identifier")
    previous_delivery_id: Optional[str] = Field(None, description="Baseline delivery to compare against")


class AskQuestionRequest(BaseModel):
    match_id: str = Field(..., description="Unique match identifier")
    delivery_id: str = Field(..., description="Contextual delivery identifier")
    question: str = Field(..., description="User's natural language question regarding field or tactics")


class TacticalExplanationResponse(BaseModel):
    summary: str = Field(..., description="Concise tactical overview")
    possible_reasons: List[str] = Field(default_factory=list, description="Plausible tactical reasons based on cricket orthodoxy")
    protected_regions: List[str] = Field(default_factory=list, description="Field regions covered by placement")
    potentially_exposed_regions: List[str] = Field(default_factory=list, description="Areas left vacant or vulnerable to scoring")
    supporting_evidence: List[str] = Field(default_factory=list, description="Empirical evidence from match telemetry & player records")
    assumptions: List[str] = Field(default_factory=list, description="Assumptions made about match tactics without verified source")
    limitations: List[str] = Field(default_factory=list, description="Epistemic limitations of analysis")
    confidence_label: str = Field(default="Limited evidence", description="Confidence label (e.g. 'Limited evidence', 'Moderate evidence')")
    
    # Metadata
    is_ai_generated: bool = Field(default=True, description="Whether generated by Gemini API or grounded fallback")
    model_used: Optional[str] = Field(default="gemini-2.0-flash", description="Model version used")
    delivery_id: Optional[str] = None
    configuration_name: Optional[str] = None
    query: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)

